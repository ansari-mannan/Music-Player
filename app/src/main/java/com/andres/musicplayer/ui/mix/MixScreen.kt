/** Blends moods into a mix: a slider per tag, weighted random sampling. */
@Composable
fun MixScreen(
    repo: SongRepository,
    player: PlayerState,
    onOpenNowPlaying: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val songs by repo.allSongsWithTags.collectAsState(initial = emptyList())
    val tags by repo.allTags.collectAsState(initial = emptyList())
    val scope = rememberCoroutineScope()

    // Weights always sum to 100: moving one slider proportionally pushes the rest.
    // Seeded equally when the moods load, so the blend starts balanced and "alive".
    val weights = remember(tags.map { it.id }) {
        mutableStateMapOf<Long, Float>().apply {
            if (tags.isNotEmpty()) {
                val each = 100f / tags.size
                tags.forEach { put(it.id, each) }
            }
        }
    }
    var sizeText by remember { mutableStateOf("30") }
    var generated by remember { mutableStateOf<MixResult?>(null) }
    var note by remember { mutableStateOf<String?>(null) }
    var showSave by remember { mutableStateOf(false) }

    if (tags.isEmpty()) {
        EmptyState(
            title = "No moods yet",
            body = "Tag some songs with moods first, then blend them into a mix here.",
            modifier = modifier,
        )
        return
    }

    val totalWeight = tags.sumOf { (weights[it.id] ?: 0f).toDouble() }.toFloat()
    val requestedSize = sizeText.toIntOrNull() ?: 0
    val sizeError = when {
        sizeText.isBlank() -> "Enter a mix size."
        requestedSize <= 0 -> "Mix size must be at least 1."
        else -> null
    }
    val canGenerate = sizeError == null && totalWeight > 0f && songs.isNotEmpty()

    Column(modifier = modifier.fillMaxSize()) {
        Column(modifier = Modifier.padding(16.dp)) {
            OutlinedTextField(
                value = sizeText,
                onValueChange = {
                    sizeText = it.filter(Char::isDigit).take(3)
                    // Editing the size invalidates any previous result.
                    generated = null
                },
                label = { Text("Mix size (songs)") },
                singleLine = true,
                isError = sizeError != null,
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
            )
            if (sizeError != null) {
                Text(
                    sizeError,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.error,
                    modifier = Modifier.padding(top = 4.dp),
                )
            }
            Spacer(Modifier.size(8.dp))
            Text(
                "Set how much of each mood to blend:",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )

            tags.forEach { tag ->
                val w = weights[tag.id] ?: 0f
                val share = if (totalWeight > 0f && w > 0f) {
                    "${(w / totalWeight * 100).roundToInt()}%"
                } else {
                    "—"
                }
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(top = 8.dp),
                    horizontalArrangement = Arrangement.SpaceBetween,
                ) {
                    Text(tag.name, style = MaterialTheme.typography.titleSmall)
                    Text(share, style = MaterialTheme.typography.titleSmall, color = MaterialTheme.colorScheme.primary)
                }
                Slider(
                    value = w,
                    valueRange = 0f..100f,
                    onValueChange = {
                        redistributeWeights(weights, tags.map { t -> t.id }, tag.id, it)
                        generated = null
                    },
                )
            }

            Spacer(Modifier.size(8.dp))
            Button(
                onClick = {
                    generated = generateMix(
                        songs = songs,
                        weights = weights,
                        totalWeight = totalWeight,
                        size = requestedSize.coerceIn(1, 500),
                    )
                    note = generated?.note
                },
                enabled = canGenerate,
                modifier = Modifier.fillMaxWidth(),
            ) {
                Text("Generate mix")
            }
        }
        HorizontalDivider()

        generated?.let { result ->
            val tagNames = remember(tags) { tags.associate { it.id to it.name } }
            Column(modifier = Modifier.padding(16.dp)) {
                if (result.songs.isEmpty()) {
                    Text(
                        "No songs matched those moods.",
                        style = MaterialTheme.typography.titleMedium,
                    )
                } else {
                    Text(
                        text = if (result.songs.size == 1) "1 song" else "${result.songs.size} songs",
                        style = MaterialTheme.typography.titleMedium,
                    )
                    val breakdown = result.breakdown.entries
                        .sortedByDescending { it.value }
                        .joinToString(", ") { "${it.value} ${tagNames[it.key] ?: "?"}" }
                    if (breakdown.isNotEmpty()) {
                        Text(
                            breakdown,
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.padding(top = 4.dp),
                        )
                    }
                    note?.let {
                        Text(
                            it,
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.padding(top = 4.dp),
                        )
                    }
                    Spacer(Modifier.size(12.dp))
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        Button(
                            onClick = {
                                player.play(result.songs.first(), result.songs)
                                onOpenNowPlaying()
                            },
                        ) { Text("Play now") }
                        TextButton(
                            onClick = { player.play(result.songs.first(), result.songs) },
                        ) { Text("Replace queue") }
                    }
                    TextButton(onClick = { showSave = true }) { Text("Save as playlist") }
                }
            }
        }
    }

    if (showSave) {
        val mix = generated?.songs.orEmpty()
        PlaylistNameDialog(
            title = "Save mix as playlist",
            initial = "My Mix",
            onDismiss = { showSave = false },
            onConfirm = { name ->
                scope.launch {
                    val id = repo.createPlaylist(name)
                    repo.addSongsToPlaylist(id, mix.map { it.song.id })
                }
                showSave = false
                note = "Saved to Playlists."
            },
        )
    }
}

/**
 * Sets [changed] to [newValue] (0..100) and rescales every other weight so the whole
 * set still sums to 100 — the visual "push the others back" effect. If the others are
 * all at zero, the remainder is shared equally so they spring back together.
 */
private fun redistributeWeights(
    weights: MutableMap<Long, Float>,
    ids: List<Long>,
    changed: Long,
    newValue: Float,
) {
    val v = newValue.coerceIn(0f, 100f)
    val others = ids.filter { it != changed }
    if (others.isEmpty()) {
        weights[changed] = 100f
        return
    }
    val remaining = 100f - v
    val othersTotal = others.sumOf { (weights[it] ?: 0f).toDouble() }.toFloat()
    if (othersTotal <= 0f) {
        val each = remaining / others.size
        others.forEach { weights[it] = each }
    } else {
        val scale = remaining / othersTotal
        others.forEach { weights[it] = (weights[it] ?: 0f) * scale }
    }
    weights[changed] = v
}

private data class MixResult(
    val songs: List<SongWithTags>,
    val note: String?,
    /** Number of songs contributed by each mood (tag id → count). */
    val breakdown: Map<Long, Int>,
)

/**
 * Weighted random sampling: each mood contributes a share of [size] proportional
 * to its slider weight. No song repeats (a song shared across moods is used once);
 * if a mood's pool is too small, takes what's available. The result is shuffled.
 */
private fun generateMix(
    songs: List<SongWithTags>,
    weights: Map<Long, Float>,
    totalWeight: Float,
    size: Int,
): MixResult {
    val active = weights.filterValues { it > 0f }
    if (active.isEmpty() || totalWeight <= 0f) return MixResult(emptyList(), null, emptyMap())

    val pickedIds = HashSet<Long>()
    val result = mutableListOf<SongWithTags>()
    val breakdown = mutableMapOf<Long, Int>()
    var shortfall = false

    active.forEach { (tagId, weight) ->
        val count = (size * weight / totalWeight).roundToInt()
        if (count <= 0) return@forEach
        val pool = songs.filter { s ->
            s.song.id !in pickedIds && s.tags.any { it.id == tagId }
        }.shuffled()
        if (pool.size < count) shortfall = true
        pool.take(count).forEach {
            pickedIds += it.song.id
            result += it
        }
        if (pool.size > 0) breakdown[tagId] = minOf(count, pool.size)
    }

    result.shuffle()
    val msg = if (shortfall) "Some moods had fewer songs than requested." else null
    return MixResult(result, msg, breakdown)
}
