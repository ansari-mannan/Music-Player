package com.andres.musicplayer.data.youtube

import android.util.Log
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONObject
import java.util.concurrent.TimeUnit

/**
 * Real release metadata for one video, as YouTube Music itself describes it, rather than
 * as guessed from a video title. Any field may be null.
 */
data class MusicMetadata(
    val track: String? = null,
    val artist: String? = null,
    val album: String? = null,
) {
    /** True when this carries something the title-parsing heuristics cannot work out. */
    val isUsable: Boolean get() = !artist.isNullOrBlank() || !album.isNullOrBlank()
}

/**
 * Looks up structured track metadata for a video id.
 *
 * The whole point of the interface is that the implementation is replaceable: bundling
 * yt-dlp through Chaquopy would give strictly better metadata, and was rejected only over
 * its ~15-25 MB per ABI and slower cold start. If that trade ever looks worth making, a
 * second implementation drops in here and [com.andres.musicplayer.download.DownloadEngine]
 * does not change.
 *
 * **Implementations must never throw.** This is enrichment; a download that transferred
 * perfectly must never fail because a metadata lookup didn't.
 */
interface MetadataResolver {
    suspend fun resolve(videoId: String): MusicMetadata?
}

/**
 * Asks `music.youtube.com`'s InnerTube `player` endpoint what a video really is.
 *
 * This is the same endpoint yt-dlp's YouTube Music handling reads, called directly over
 * OkHttp — no Python runtime, no extra megabytes. The `WEB_REMIX` client context is what
 * makes YouTube answer as *YouTube Music* rather than as YouTube: only then does the
 * response carry `musicVideoType`, which is the flag that separates a real catalogue
 * release from someone's upload.
 *
 * ### Where the artist and album actually come from
 *
 * Not from a tidy JSON field — YouTube does not expose one. For an auto-generated
 * catalogue upload (`MUSIC_VIDEO_TYPE_ATV`, the "… - Topic" channels) the structured
 * metadata is laid out in `shortDescription` in a fixed machine-written shape, ending in
 * "Auto-generated by YouTube." That block is the authoritative source, and it is what
 * [parseAutoGeneratedDescription] reads.
 *
 * Anything that is *not* an auto-generated upload deliberately returns null rather than a
 * half-guess: for an official music video the channel name is often a label or a VEVO
 * account, which is worse than what
 * [com.andres.musicplayer.download.deriveTags] already works out from the title.
 */
class MusicMetadataResolver(
    private val http: OkHttpClient = defaultClient(),
    /** Overridden only by tests, which point it at a local server. */
    private val baseUrl: String = MUSIC_BASE,
) : MetadataResolver {

    override suspend fun resolve(videoId: String): MusicMetadata? = withContext(Dispatchers.IO) {
        try {
            val body = request(videoId) ?: return@withContext null
            parseMusicMetadata(body)
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (e: Exception) {
            // Swallowed on purpose, exactly like CoverArtFetcher: a slow or broken
            // lookup costs this track its nice tags, never the download itself.
            Log.w(TAG, "YouTube Music lookup failed for $videoId", e)
            null
        }
    }

    private fun request(videoId: String): String? {
        val payload = JSONObject().apply {
            put("videoId", videoId)
            put(
                "context",
                JSONObject().put(
                    "client",
                    JSONObject().apply {
                        put("clientName", CLIENT_NAME)
                        put("clientVersion", CLIENT_VERSION)
                        put("hl", "en")
                        put("gl", "US")
                    },
                ),
            )
        }.toString()

        val request = Request.Builder()
            .url("$baseUrl/youtubei/v1/player?key=$API_KEY&prettyPrint=false")
            .post(payload.toRequestBody(JSON_MEDIA_TYPE))
            .header("Origin", MUSIC_BASE)
            .header("Referer", "$MUSIC_BASE/")
            .header("User-Agent", USER_AGENT)
            .header("X-YouTube-Client-Name", CLIENT_ID)
            .header("X-YouTube-Client-Version", CLIENT_VERSION)
            .build()

        return http.newCall(request).execute().use { response ->
            if (!response.isSuccessful) {
                Log.w(TAG, "YouTube Music player endpoint returned HTTP ${response.code}")
                return@use null
            }
            response.body?.string()
        }
    }

    companion object {
        private const val TAG = "MusicMetadata"

        const val MUSIC_BASE = "https://music.youtube.com"

        /**
         * The public InnerTube client identity for YouTube Music's web player. Not a
         * secret — it ships in the page source of music.youtube.com and is the same
         * constant every InnerTube client uses.
         */
        private const val API_KEY = "AIzaSyC9XL3ZjWddXya6X74dJoCTL-WEYFDNX30"
        private const val CLIENT_NAME = "WEB_REMIX"
        private const val CLIENT_ID = "67"
        private const val CLIENT_VERSION = "1.20240403.01.00"

        private const val USER_AGENT =
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:127.0) Gecko/20100101 Firefox/127.0"

        private val JSON_MEDIA_TYPE = "application/json; charset=utf-8".toMediaType()

        /**
         * Short on purpose. This lookup sits directly in front of a finished download, so
         * every second it spends is a second the file isn't in the library yet — and its
         * answer is a bonus, not a requirement.
         */
        fun defaultClient(): OkHttpClient = OkHttpClient.Builder()
            .connectTimeout(4, TimeUnit.SECONDS)
            .readTimeout(4, TimeUnit.SECONDS)
            .callTimeout(5, TimeUnit.SECONDS)
            .build()
    }
}

/**
 * Reads a `WEB_REMIX` player response. Returns null for anything that isn't an
 * auto-generated YouTube Music release, and for any JSON that doesn't parse.
 *
 * Split out from the HTTP call so the shapes YouTube really returns can be tested as
 * fixtures rather than over a socket.
 */
internal fun parseMusicMetadata(json: String): MusicMetadata? {
    val root = runCatching { JSONObject(json) }.getOrNull() ?: return null
    val details = root.optJSONObject("videoDetails") ?: return null

    // No musicVideoType at all means YouTube answered as plain YouTube — either the
    // client context didn't take, or this video isn't in the music catalogue.
    val musicVideoType = details.optString("musicVideoType").trimOrNull() ?: return null
    if (musicVideoType != TYPE_AUTO_GENERATED) return null

    val fromDescription = parseAutoGeneratedDescription(details.optString("shortDescription"))
    val author = details.optString("author").trimOrNull()?.removeSuffix(TOPIC_SUFFIX)?.trim()

    val metadata = MusicMetadata(
        track = fromDescription?.track ?: details.optString("title").trimOrNull(),
        // The description's credit line is more precise than the channel: it names
        // featured artists, which the channel name never does.
        artist = fromDescription?.artist ?: author,
        album = fromDescription?.album,
    )
    return metadata.takeIf { it.isUsable }
}

/**
 * Pulls track, artist and album out of the fixed block YouTube writes into the
 * description of an auto-generated upload:
 *
 * ```
 * Provided to YouTube by Some Distributor
 *
 * Around the World · Daft Punk
 *
 * Homework
 *
 * ℗ 1997 Some Label
 *
 * Auto-generated by YouTube.
 * ```
 *
 * The trailing "Auto-generated by YouTube." is the gate: without it this is a human's
 * description, where a stray "·" means nothing and reading an album out of it would
 * invent one. Returns null unless a credit line is actually found.
 */
internal fun parseAutoGeneratedDescription(description: String): MusicMetadata? {
    if (!description.contains(AUTO_GENERATED_MARKER)) return null

    val blocks = description.split(BLANK_LINE)
        .map { it.trim() }
        .filter { it.isNotEmpty() }

    val creditIndex = blocks.indexOfFirst { it.contains(CREDIT_SEPARATOR) }
    if (creditIndex < 0) return null

    val credit = blocks[creditIndex]
        .split(CREDIT_SEPARATOR)
        .map { it.trim() }
        .filter { it.isNotEmpty() }
    if (credit.size < 2) return null

    // "Track · Artist · Featured Artist" — everything after the track is a performer.
    val track = credit.first()
    val artist = credit.drop(1).joinToString(", ")

    // The album is the very next block, when there is one that isn't boilerplate.
    val album = blocks.getOrNull(creditIndex + 1)?.takeUnless { it.isBoilerplate() }

    return MusicMetadata(track = track, artist = artist, album = album)
}

/** Lines YouTube adds after the album that must never be mistaken for one. */
private fun String.isBoilerplate(): Boolean =
    startsWith("℗") ||
        startsWith("©") ||
        startsWith("Released on", ignoreCase = true) ||
        startsWith("Auto-generated", ignoreCase = true) ||
        contains(CREDIT_SEPARATOR)

private fun String.trimOrNull(): String? = trim().takeIf { it.isNotEmpty() }

/** An auto-generated catalogue upload — the "… - Topic" channels. */
private const val TYPE_AUTO_GENERATED = "MUSIC_VIDEO_TYPE_ATV"

private const val AUTO_GENERATED_MARKER = "Auto-generated by YouTube"
private const val TOPIC_SUFFIX = " - Topic"

/** A middle dot, not a hyphen: YouTube uses U+00B7 to separate the credits. */
private const val CREDIT_SEPARATOR = "·"

private val BLANK_LINE = Regex("""\r?\n\s*\r?\n""")
