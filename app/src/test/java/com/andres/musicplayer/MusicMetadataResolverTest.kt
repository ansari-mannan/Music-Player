package com.andres.musicplayer

import com.andres.musicplayer.data.youtube.MusicMetadataResolver
import com.andres.musicplayer.data.youtube.parseAutoGeneratedDescription
import com.andres.musicplayer.data.youtube.parseMusicMetadata
import kotlinx.coroutines.runBlocking
import okhttp3.OkHttpClient
import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import org.json.JSONObject
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test

/**
 * Reading real release metadata out of a YouTube Music `player` response.
 *
 * Fixtures rather than the network, for the same reason [TrackTagsTest] uses fixtures:
 * what needs pinning is the *judgement* — which responses are trustworthy enough to
 * override the title-parsing heuristics, and which must be refused so the heuristics get
 * their turn. A response that YouTube changes tomorrow would break the app either way;
 * one that is misread today breaks every tag silently.
 */
class MusicMetadataResolverTest {

    // --- What the response says ----------------------------------------------------

    @Test
    fun `an auto-generated release yields track, artist and album`() {
        val metadata = parseMusicMetadata(
            playerResponse(
                title = "Around the World",
                author = "Daft Punk",
                musicVideoType = "MUSIC_VIDEO_TYPE_ATV",
                description = autoGenerated(
                    track = "Around the World",
                    artists = "Daft Punk",
                    album = "Homework",
                ),
            ),
        )

        assertEquals("Around the World", metadata?.track)
        assertEquals("Daft Punk", metadata?.artist)
        assertEquals("Homework", metadata?.album)
    }

    @Test
    fun `featured artists in the credit line are all kept`() {
        // The reason the description beats the channel name: a "… - Topic" channel is
        // one name, and the credit line is the full billing.
        val metadata = parseMusicMetadata(
            playerResponse(
                title = "Get Lucky",
                author = "Daft Punk",
                musicVideoType = "MUSIC_VIDEO_TYPE_ATV",
                description = autoGenerated(
                    track = "Get Lucky",
                    artists = "Daft Punk · Pharrell Williams · Nile Rodgers",
                    album = "Random Access Memories",
                ),
            ),
        )

        assertEquals("Daft Punk, Pharrell Williams, Nile Rodgers", metadata?.artist)
    }

    @Test
    fun `a release with no album block does not invent one from the copyright line`() {
        val metadata = parseMusicMetadata(
            playerResponse(
                title = "Some Single",
                author = "Some Artist",
                musicVideoType = "MUSIC_VIDEO_TYPE_ATV",
                description = "Provided to YouTube by Some Distributor\n\n" +
                    "Some Single · Some Artist\n\n" +
                    "℗ 2019 Some Label\n\n" +
                    "Auto-generated by YouTube.",
            ),
        )

        assertEquals("Some Artist", metadata?.artist)
        assertNull("the ℗ line is not an album", metadata?.album)
    }

    @Test
    fun `a Topic suffix on the channel is never written into the artist tag`() {
        // Falls back to the channel because the description carries no credit line.
        val metadata = parseMusicMetadata(
            playerResponse(
                title = "Chandelier",
                author = "Sia - Topic",
                musicVideoType = "MUSIC_VIDEO_TYPE_ATV",
                description = "Auto-generated by YouTube.",
            ),
        )

        assertEquals("Sia", metadata?.artist)
    }

    // --- What the response refuses to say --------------------------------------------

    @Test
    fun `a plain YouTube video is refused so the heuristics get their turn`() {
        // No musicVideoType at all: this is not in the music catalogue.
        assertNull(
            parseMusicMetadata(
                playerResponse(
                    title = "Some vlog",
                    author = "Some Channel",
                    musicVideoType = null,
                    description = "hey everyone welcome back",
                ),
            ),
        )
    }

    @Test
    fun `an official music video is refused rather than trusting the label channel`() {
        // OMV means a real upload by a real channel — very often a label or VEVO
        // account. "DaftPunkVEVO" is worse than what deriveTags reads off the title,
        // so this must not win.
        assertNull(
            parseMusicMetadata(
                playerResponse(
                    title = "Daft Punk - Around the World (Official Video)",
                    author = "DaftPunkVEVO",
                    musicVideoType = "MUSIC_VIDEO_TYPE_OMV",
                    description = "The official video.",
                ),
            ),
        )
    }

    @Test
    fun `a human-written description is never mined for metadata`() {
        // A dot in someone's own description means nothing. Without the auto-generated
        // marker this must fall through, not read "Track · Artist" out of prose.
        assertNull(
            parseAutoGeneratedDescription(
                "my setup · gear list below\n\nBought at Some Shop\n\nthanks for watching",
            ),
        )
    }

    @Test
    fun `malformed and empty responses are refused rather than crashing`() {
        assertNull(parseMusicMetadata("<html>captive portal</html>"))
        assertNull(parseMusicMetadata(""))
        assertNull(parseMusicMetadata("{}"))
        assertNull(parseMusicMetadata("""{"videoDetails":{}}"""))
        assertNull(parseMusicMetadata("""{"playabilityStatus":{"status":"ERROR"}}"""))
    }

    @Test
    fun `a response with a type but nothing usable in it is refused`() {
        // Enrichment that carries neither artist nor album is not enrichment.
        assertNull(
            parseMusicMetadata(
                playerResponse(
                    title = "Untitled",
                    author = "",
                    musicVideoType = "MUSIC_VIDEO_TYPE_ATV",
                    description = "Auto-generated by YouTube.",
                ),
            ),
        )
    }

    // --- Failing soft over HTTP -------------------------------------------------------

    private lateinit var server: MockWebServer

    @Before
    fun setUp() {
        server = MockWebServer().apply { start() }
    }

    @After
    fun tearDown() = server.shutdown()

    @Test
    fun `the lookup asks YouTube Music as a music client`() {
        server.enqueue(
            MockResponse().setBody(
                playerResponse(
                    title = "Around the World",
                    author = "Daft Punk",
                    musicVideoType = "MUSIC_VIDEO_TYPE_ATV",
                    description = autoGenerated("Around the World", "Daft Punk", "Homework"),
                ),
            ),
        )

        val metadata = runBlocking { resolver().resolve("dQw4w9WgXcQ") }
        assertEquals("Homework", metadata?.album)

        val request = server.takeRequest()
        assertTrue(request.path!!.contains("/youtubei/v1/player"))
        // WEB_REMIX is what makes YouTube answer as YouTube Music; without it the
        // response carries no musicVideoType and every lookup would come back null.
        assertTrue(request.body.readUtf8().contains("WEB_REMIX"))
        assertEquals("67", request.getHeader("X-YouTube-Client-Name"))
    }

    @Test
    fun `an http failure returns null instead of throwing`() {
        // The contract the download path depends on: enrichment never fails a download.
        server.enqueue(MockResponse().setResponseCode(500).setBody("upstream exploded"))
        assertNull(runBlocking { resolver().resolve("dQw4w9WgXcQ") })
    }

    @Test
    fun `a body that is not json returns null instead of throwing`() {
        server.enqueue(MockResponse().setResponseCode(200).setBody("<html>nope</html>"))
        assertNull(runBlocking { resolver().resolve("dQw4w9WgXcQ") })
    }

    @Test
    fun `an unreachable server returns null instead of throwing`() {
        val url = server.url("/").toString().trimEnd('/')
        server.shutdown()
        val offline = MusicMetadataResolver(http = OkHttpClient(), baseUrl = url)
        assertNull(runBlocking { offline.resolve("dQw4w9WgXcQ") })
        // Started again so the @After shutdown has something to close.
        server = MockWebServer().apply { start() }
    }

    // --- Fixtures ----------------------------------------------------------------------

    private fun resolver() = MusicMetadataResolver(
        http = OkHttpClient(),
        baseUrl = server.url("/").toString().trimEnd('/'),
    )

    /** Built through org.json so the description's newlines are escaped exactly as YouTube's are. */
    private fun playerResponse(
        title: String,
        author: String,
        musicVideoType: String?,
        description: String,
    ): String = JSONObject().put(
        "videoDetails",
        JSONObject().apply {
            put("videoId", "dQw4w9WgXcQ")
            put("title", title)
            put("author", author)
            put("shortDescription", description)
            if (musicVideoType != null) put("musicVideoType", musicVideoType)
        },
    ).toString()

    /** The fixed block YouTube writes into every auto-generated catalogue upload. */
    private fun autoGenerated(track: String, artists: String, album: String?) = buildString {
        append("Provided to YouTube by Because Music\n\n")
        append("$track · $artists\n\n")
        if (album != null) append("$album\n\n")
        append("℗ 1997 Daft Life Ltd.\n\n")
        append("Released on: 1997-01-20\n\n")
        append("Auto-generated by YouTube.")
    }
}
