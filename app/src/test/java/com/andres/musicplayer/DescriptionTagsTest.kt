package com.andres.musicplayer

import com.andres.musicplayer.data.youtube.descriptionText
import com.andres.musicplayer.data.youtube.htmlToPlainText
import com.andres.musicplayer.data.youtube.parseAutoGeneratedDescription
import com.andres.musicplayer.download.deriveTags
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.schabi.newpipe.extractor.stream.Description

/**
 * Reading tags out of the description NewPipe hands back with the stream, and turning a
 * "Title - Artist" video title the right way round.
 */
class DescriptionTagsTest {

    /** The auto-generated block as NewPipe returns it for YouTube: HTML, links and all. */
    private val htmlDescription =
        "Provided to YouTube by Parlophone UK<br><br>" +
            "Around the World · <a href=\"https://www.youtube.com/channel/x\">Daft Punk</a><br><br>" +
            "Homework<br><br>" +
            "℗ 1997 Daft Life Ltd.<br><br>" +
            "Released on: 1997-01-20<br><br>" +
            "Auto-generated by YouTube."

    @Test
    fun `an HTML description is read back to the plain lines YouTube wrote`() {
        assertEquals("Tom &amp; Jerry\nline two", htmlToPlainText("Tom &amp;amp; Jerry<br/>line two"))
        assertEquals("Rock & Roll · \"Live\" 's", htmlToPlainText("Rock &amp; Roll &middot; &quot;Live&quot; &#39;s"))
        assertEquals("a b", htmlToPlainText("a&#x20;b"))
    }

    @Test
    fun `the auto-generated block parses straight from NewPipe's HTML`() {
        val text = descriptionText(htmlDescription, Description.HTML)!!
        val music = parseAutoGeneratedDescription(text)!!
        assertEquals("Around the World", music.track)
        assertEquals("Daft Punk", music.artist)
        assertEquals("Homework", music.album)
    }

    @Test
    fun `plain text descriptions are left alone and empty ones are null`() {
        assertEquals("a<br>b", descriptionText("a<br>b", Description.PLAIN_TEXT))
        assertNull(descriptionText("   ", Description.HTML))
        assertNull(descriptionText(null, null))
    }

    @Test
    fun `a Title - Artist video is turned round when the artist is the channel`() {
        val tags = deriveTags("Chandelier - Sia", "SiaVEVO", null)
        assertEquals("Chandelier", tags.title)
        assertEquals("Sia", tags.artist)
    }

    @Test
    fun `an Artist - Title video from the artist's own channel is left as it is`() {
        val tags = deriveTags("Sia - Chandelier", "Sia Official", null)
        assertEquals("Chandelier", tags.title)
        assertEquals("Sia", tags.artist)
    }

    @Test
    fun `a fan page's upload keeps the usual Artist - Title reading`() {
        val tags = deriveTags("Sia - Chandelier", "Best Lyrics 4K", null)
        assertEquals("Chandelier", tags.title)
        assertEquals("Sia", tags.artist)
    }
}
